namespace EvilHop.Tests.Primitives;

public class EvilStringTests
{
    public static IEnumerable<object[]> EvilStringData =>
    [
        [new byte[] { 0x00, 0x00 }, ""],
        [new byte[] { 0x54, 0x75, 0x65, 0x20, 0x41, 0x75, 0x67, 0x20, 0x30, 0x36, 0x20,
            0x31, 0x32, 0x3A, 0x32, 0x31, 0x3A, 0x31, 0x34, 0x20, 0x32, 0x30, 0x30, 0x32, 0x0A, 0x00,
        }, "Tue Aug 06 12:21:14 2002\n"],
        [new byte[] { 0x5F, 0x50, 0x52, 0x4A, 0x5F, 0x56, 0x57, 0x45, 0x50, 0x5F, 0x57,
            0x49, 0x54, 0x43, 0x48, 0x44, 0x4F, 0x43, 0x54, 0x4F, 0x52, 0x00,
        }, "_PRJ_VWEP_WITCHDOCTOR"],
        [new byte[] { 0x63, 0x73, 0x64, 0x5F, 0x6A, 0x75, 0x6D, 0x70, 0x73, 0x70, 0x72,
            0x69, 0x6E, 0x67, 0x5F, 0x30, 0x30, 0x2E, 0x61, 0x6E, 0x6D, 0x00,
        }, "csd_jumpspring_00.anm"],
        [new byte[] { 0x5C, 0x5C, 0x6A, 0x6F, 0x62, 0x5C, 0x73, 0x64, 0x32, 0x5C, 0x5C,
            0x63, 0x67, 0x5C, 0x63, 0x68, 0x72, 0x5C, 0x70, 0x32, 0x5C, 0x73, 0x64, 0x5C, 0x6C, 0x61,
            0x74, 0x65, 0x73, 0x74, 0x5C, 0x63, 0x73, 0x64, 0x5F, 0x6A, 0x75, 0x6D, 0x70, 0x73, 0x70,
            0x72, 0x69, 0x6E, 0x67, 0x5F, 0x30, 0x30, 0x2E, 0x61, 0x6E, 0x6D, 0x00, 0x00,
        }, "\\\\job\\sd2\\\\cg\\chr\\p2\\sd\\latest\\csd_jumpspring_00.anm"],
    ];

    [Theory]
    [MemberData(nameof(EvilStringData))]
    public void EvilString_ReadEvilString_ExpectedValue(byte[] data, string expected)
    {
        BinaryReader reader = new(new MemoryStream(data));

        string value = reader.ReadEvilString();

        Assert.Equal(expected, value);
    }

    [Fact]
    public void EvilString_ReadEvilString_NonZeroPaddingByte_ThrowsInvalidDataException()
    {
        BinaryReader reader = new(new MemoryStream([0x41, 0x42, 0x00, 0x01]));

        var ex = Assert.Throws<InvalidDataException>(() => reader.ReadEvilString());

        Assert.Equal("Expected 2 null bytes after string of length 2.", ex.Message);
    }

    [Theory]
    [MemberData(nameof(EvilStringData))]
    public void EvilString_WriteEvilString_ExpectedBytes(byte[] data, string value)
    {
        using MemoryStream stream = new();
        using BinaryWriter writer = new(stream);

        writer.WriteEvilString(value);

        Assert.Equal(data, stream.ToArray());
    }
}
